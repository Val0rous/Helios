@Composable
fun rememberChartIconDrawer(
    chartType: Charts,
    moonPhase: MoonPhaseAppearance = MoonPhaseAppearance.Full,
): DrawScope.(iconSize: Float, isBelow: Boolean) -> Unit {
    // 1. Resolve Sun & fallback painters once (Moon uses procedural MoonPhaseIcon geometry)
    val sunFilled = painterResource(id = R.drawable.ic_brightness_empty_filled)
    val sunOutline = painterResource(id = R.drawable.ic_brightness_empty_200_high_emphasis)
    val indicatorPainter = painterResource(id = R.drawable.ic_circle_filled)
    val moonPath = remember { Path() }

    // 2. Resolve themed icon & border colors generated by MaterialColorEngine
    val colors = LocalCustomColors.current

    // 3. Return a reusable DrawScope extension lambda
    return remember(chartType, colors, moonPhase) {
        { iconSize, isBelow ->
            val sizeObj = Size(iconSize, iconSize)
            // Draw the main chart icon
            when (chartType) {
                is Charts.Sun -> {
                    val color = if (isBelow) colors.sun.copy(alpha = ChartAlphas.ICON_BELOW_HORIZON) else colors.sun
                    // Base filled sun
                    with(sunFilled) {
                        draw(size = sizeObj, colorFilter = ColorFilter.tint(color))
                    }
                    // Themed border overlay for above-horizon sun
                    if (!isBelow) {
                        with(sunOutline) {
                            draw(size = sizeObj, colorFilter = ColorFilter.tint(colors.sunBorder))
                        }
                    }
                }

                is Charts.Moon -> {
                    drawMoonPhaseIcon(
                        iconSize = iconSize,
                        phase = moonPhase,
                        fillColor = colors.moon,
                        borderColor = colors.moonBorder,
                        backgroundColor = colors.moonUnlit,
                        isDimmed = isBelow,
                        reusablePath = moonPath,
                    )
                }

                else -> {
                    val color = if (isBelow) Color.Red else colors.sun// TODO
                    with(indicatorPainter) {
                        draw(size = sizeObj, colorFilter = ColorFilter.tint(color))
                    }
                }
            }
        }
    }
}


fun DrawScope.paintIcon(
    currentXPx: Float,
    currentY: Float,
    currentYPx: Float,
    zeroYPixel: Float,
    chartType: Charts,
    coordinates: Coordinates?,
    drawChartIcon: DrawScope.(Float, Boolean) -> Unit
) {
    val className = chartType.javaClass.simpleName
    val isUp = when {
        className.contains("Elevation") || className.contains("Trajectory") -> {
            when (chartType) {
                is Charts.Sun -> currentY >= coordinates!!.sunApparentHorizonAlt.toFloat()
                is Charts.Moon -> currentY >= coordinates!!.moonApparentHorizonAlt.toFloat()
                else -> currentY >= 0f
            }
        }
        // Protect the boolean checks against NaN! (Night metrics are 0f or NaN)
        className.contains("UvIntensity") -> currentY.isFinite() && currentY >= 0.01f
        className.contains("Shadows") -> currentY.isFinite() && currentY > 0f
        className.contains("ColorTemperature") -> currentY.isFinite() && currentY >= 1800f
        className.contains("AirMass") -> currentY.isFinite() && currentY > 0f
        else -> !currentY.isNaN() && currentY > 0f
    }

    if (isUp) {
        val iconSize = 24.dp.toPx()

        clipRect(bottom = (zeroYPixel - 2f)) {
            translate(
                left = currentXPx - iconSize / 2,
                top = currentYPx - iconSize / 2
            ) {
                drawChartIcon(iconSize, false)
            }
        }
    } else {
        val iconSize = 12.dp.toPx()
        translate(
            left = currentXPx - iconSize / 2,
            top = currentYPx - iconSize / 2
        ) {
            drawChartIcon(iconSize, true)
        }
    }
}

@Composable
fun rememberIconBitmapDescriptor(
    isAbove: Boolean,
    drawer: DrawScope.(Float, Boolean) -> Unit
): BitmapDescriptor {
    val density = LocalDensity.current

    // Only re-draw the bitmap if the elevation state, screen density, or theme colors (drawer) change
    return remember(isAbove, density, drawer) {
        val sizeDp = if (isAbove) 24f else 12f
        val sizePx = with(density) { sizeDp.dp.toPx() }
        val intSize = sizePx.toInt().coerceAtLeast(1)

        // 1. Create a blank Compose ImageBitmap
        val imageBitmap = ImageBitmap(intSize, intSize)
        val canvas = androidx.compose.ui.graphics.Canvas(imageBitmap)

        // 2. Open a Compose DrawScope and execute the lambda from ChartIconDrawer!
        CanvasDrawScope().draw(
            density = density,
            layoutDirection = LayoutDirection.Ltr,
            canvas = canvas,
            size = androidx.compose.ui.geometry.Size(sizePx, sizePx)
        ) {
            drawer(sizePx, !isAbove) // Pass the size and the 'isBelow' boolean
        }

        // 3. Convert to an Android Bitmap for Google Maps
        BitmapDescriptorFactory.fromBitmap(imageBitmap.asAndroidBitmap())
    }
}